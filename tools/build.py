"""Produce deterministic packages and the two generated catalogue copies."""

import hashlib
import json
import sys
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from gamma_archipelago.configuration import (  # noqa: E402
    CHECK_OPTIONS,
    GEAR_OPTIONS,
    GOALS,
    QUANTITY_OPTIONS,
    REWARD_OPTIONS,
)


def generate_catalogues() -> None:
    source = ROOT / "src/gamma_archipelago/catalog.json"
    catalogue = json.loads(source.read_text(encoding="utf-8"))
    (ROOT / "apworld/gamma/catalog.json").write_bytes(source.read_bytes())
    lines = ["-- Generated by tools/build.py from src/gamma_archipelago/catalog.json."]
    lines.append("item_sections = {")
    lines.extend(f'    [{item["id"]}] = "{item["section"]}",' for item in catalogue["items"])
    lines.extend(["}", "location_by_level = {"])
    lines.extend(
        f'    ["{loc["level"]}"] = {loc["id"]},'
        for loc in catalogue["locations"]
        if loc["category"] == "checks_maps"
    )
    lines.extend(["}", "location_ids = {"])
    lines.extend(f"    {loc['id']}," for loc in catalogue["locations"])
    lines.append("}")
    lines.append("artefact_locations = {")
    for loc in catalogue["locations"]:
        if loc["category"] == "checks_artefacts":
            lines.extend(f'    ["{alias}"] = {loc["id"]},' for alias in loc["aliases"])
    lines.append("}")
    milestone = catalogue["milestones"]["checks_kill_milestones"]
    lines.append(f"kill_milestone_base = {milestone['base_id']}")
    lines.append(f"kill_milestone_maximum = {milestone['maximum']}")
    for table_name in ("mutant_classes", "mutant_sections"):
        lines.append(table_name + " = {")
        lines.extend(f'    ["{key}"] = "{value}",' for key, value in catalogue[table_name].items())
        lines.append("}")
    for category, table_name in (
        ("checks_mutant_first_kills", "mutant_locations"),
        ("checks_faction_first_kills", "faction_locations"),
    ):
        lines.append(table_name + " = {")
        lines.extend(
            f'    ["{loc["key"]}"] = {loc["id"]},'
            for loc in catalogue["locations"]
            if loc["category"] == category
        )
        lines.append("}")
    lines.append("pilot_ids = {[28052001]=true, [28052002]=true, [28052003]=true}")
    lines.append("location_categories = {")
    lines.extend(f'    [{loc["id"]}] = "{loc["category"]}",' for loc in catalogue["locations"])
    lines.extend(["}", "settlements = {"])
    for loc in catalogue["locations"]:
        for smart in loc.get("smarts", []):
            lines.append(
                f'    ["{smart}"] = {{id={loc["id"]}, level="{loc["level"]}", radius=50}},'
            )
    lines.append("}")
    limits = {
        **dict.fromkeys(CHECK_OPTIONS + REWARD_OPTIONS, 1),
        **dict.fromkeys(GEAR_OPTIONS, 2),
        **dict.fromkeys(QUANTITY_OPTIONS, 100),
        "goal": len(GOALS) - 1,
        "no_starting_weapons": 1,
    }
    lines.append("config_limits = {")
    lines.extend(f'    ["{name}"] = {limit},' for name, limit in sorted(limits.items()))
    lines.append("}")
    (ROOT / "mod/gamedata/scripts/gamma_ap_catalog.script").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
    )


def package(
    source: Path, destination: Path, prefix: str = "", extras: dict[str, Path] | None = None
) -> None:
    entries = {
        prefix + path.relative_to(source).as_posix(): path
        for path in source.rglob("*")
        if path.is_file() and "__pycache__" not in path.parts
    }
    entries.update(extras or {})
    with ZipFile(destination, "w", compression=ZIP_DEFLATED) as archive:
        for name, path in sorted(entries.items()):
            info = ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, path.read_bytes())


def main() -> None:
    generate_catalogues()
    destination = ROOT / "dist"
    destination.mkdir(exist_ok=True)
    packages = [
        destination / name
        for name in ("gamma.apworld", "gamma-archipelago-mo2.zip", "gamma-archipelago-probes.zip")
    ]
    package(ROOT / "apworld/gamma", packages[0], "gamma/")
    package(ROOT / "mod", packages[1])
    shared_path = "gamedata/scripts/gamma_ap_paths.script"
    package(ROOT / "probes", packages[2], extras={shared_path: ROOT / "mod" / shared_path})
    hashes = [f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {path.name}" for path in packages]
    (destination / "SHA256SUMS").write_text("\n".join(hashes) + "\n", encoding="ascii")
    print("Built deterministic AP world and MO2 add-on packages.")


if __name__ == "__main__":
    main()
