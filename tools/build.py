def generate_catalogues() -> None:
    source = require_safe_child(ROOT, "src/gamma_archipelago/catalog.json")
    catalogue = json.loads(source.read_text(encoding="utf-8"))
    generate_notice_strings(ROOT, catalogue)
    generate_shop_strings(ROOT, catalogue)
    require_safe_child(ROOT, "apworld/gamma/catalog.json").write_bytes(source.read_bytes())
    lines = ["-- Generated by tools/build.py from src/gamma_archipelago/catalog.json."]
    lines.extend(activity_lines(catalogue))
    lines.append("start_locations = {")
    for index, start in enumerate(catalogue["starting_locations"]):
        lines.append(
            f"    [{index}]="
            + "{"
            + ",".join(f"{name}={json.dumps(value)}" for name, value in start.items())
            + "},"
        )
    lines.append("}")
    lines.append("item_sections = {")
    lines.extend(
        f'    [{item["id"]}] = "{item["section"]}",'
        for item in catalogue["items"]
        if "section" in item
    )
    lines.extend(["}", "item_effects = {"])
    lines.extend(
        f'    [{item["id"]}] = "{item.get("effect", "item")}",' for item in catalogue["items"]
    )
    lines.extend(["}", "item_categories = {"])
    lines.extend(
        f'    [{item["id"]}] = "{item.get("category", "")}",' for item in catalogue["items"]
    )
    lines.extend(["}", "lab_levels = {"])
    lines.extend(f'    ["{level}"] = true,' for level in catalogue["x_labs"])
    lines.extend(["}", "zone_keys = {"])
    lines.extend(
        f'    ["{item["level"]}"] = "{item["permission"]}",'
        for item in catalogue["items"]
        if item.get("category") == "rewards_zone_keys"
    )
    lines.extend(["}", "gear_rewards = {"])
    lines.extend(
        f'    [{item["id"]}] = {{group="{item["group"]}", section="{item["baseline"]}"}},'
        for item in catalogue["items"]
        if "baseline" in item
    )
    lines.extend(["}", "permissions = {"])
    lines.extend(
        f'    [{item["id"]}] = "{item["permission"]}",'
        for item in catalogue["items"]
        if item.get("effect") == "unlock"
    )
    lines.extend(["}", "quest_gates = {"])
    lines.extend(f'    ["{task}"] = "{key}",' for task, key in catalogue["quest_gates"].items())
    lines.extend(["}", "skill_rewards = {"])
    lines.extend(
        f'    [{item["id"]}] = "{item["skill"]}",'
        for item in catalogue["items"]
        if item.get("effect") == "skill"
    )
    lines.extend(["}", "reputation_rewards = {"])
    for item in catalogue["items"]:
        if item.get("effect") == "reputation":
            lines.append(
                f'    [{item["id"]}] = {{faction="{item["faction"]}", '
                f"bonus={item['bonus']}, cap={item['cap']}}},"
            )
    lines.extend(
        [
            "}",
            "shared_goodwill_id = 28051309",
            "allied_goodwill_id = 28051310",
            "goodwill_factions = {",
        ]
    )
    lines.extend(
        json.dumps(item["faction"]) + ","
        for item in catalogue["items"]
        if item.get("effect") == "reputation" and item["faction"] not in {"all", "allied"}
    )
    lines.extend(["}", "stash_containers = {"])
    lines.extend(
        f'    ["{name}"] = "{level}",' for name, level in catalogue["stash_containers"].items()
    )
    lines.extend(["}", "stash_contents = {"])
    for item in catalogue["items"]:
        if item.get("effect") in {"loot_stash", "progression_stash"}:
            values = ", ".join(json.dumps(section) for section in item["contents"])
            lines.append(f"    [{item['id']}] = {{{values}}},")
    lines.extend(["}", "progression_stashes = {"])
    for item in catalogue["items"]:
        if item.get("effect") == "progression_stash":
            lines.append(f'    [{item["id"]}] = "{item["cache"]}",')
    lines.extend(["}", "location_by_level = {"])
    lines.extend(
        f'    ["{loc["level"]}"] = {loc["id"]},'
        for loc in catalogue["locations"]
        if loc["category"] == "checks_maps"
    )
    lines.extend(["}", "location_ids = {"])
    lines.extend(f"    {loc['id']}," for loc in catalogue["locations"])
    lines.append("}")
    lines.append("rank_locations = {")
    for loc in catalogue["locations"]:
        if loc["category"] == "checks_rank_milestones":
            lines.append(f'    {{id={loc["id"]}, name="{loc["key"]}", minimum={loc["minimum"]}}},')
    lines.append("}")
    for name in ("armour_kinds", "weapon_kinds", "knives"):
        lines.append(name + " = {")
        for key, value in catalogue["equipment"][name].items():
            encoded = json.dumps(value)
            lines.append(f'    ["{key}"] = {encoded},')
        lines.append("}")
    for name in ("powered_outfits", "machineguns"):
        lines.append(name + " = {")
        lines.extend(f'    ["{section}"] = true,' for section in catalogue["equipment"][name])
        lines.append("}")
    for category, name in (
        ("checks_armour_tiers", "armour_locations"),
        ("checks_weapon_tiers", "weapon_locations"),
        ("checks_knife_tiers", "knife_locations"),
    ):
        lines.append(name + " = {")
        lines.extend(
            f'    ["{loc["key"]}"] = {loc["id"]},'
            for loc in catalogue["locations"]
            if loc["category"] == category and "quota_group" not in loc
        )
        lines.append("}")
    lines.append("upgrade_locations = {")
    for group in ("firearm", "armour"):
        lines.append(f'    ["{group}"] = {{')
        lines.extend(
            f"        [{loc['threshold']}] = {loc['id']},"
            for loc in catalogue["locations"]
            if loc["category"] == "checks_gear_upgrades" and loc["key"] == group
        )
        lines.append("    },")
    lines.append("}")
    lines.append("task_functors = {")
    lines.extend(f'    ["{key}"] = "{value}",' for key, value in catalogue["task_functors"].items())
    lines.extend(["}", "quest_type_locations = {"])
    lines.extend(
        f'    ["{loc["key"]}"] = {loc["id"]},'
        for loc in catalogue["locations"]
        if loc["category"] == "checks_quest_types"
    )
    lines.extend(["}", "story_task_locations = {"])
    for loc in catalogue["locations"]:
        for task_id in loc.get("tasks", []):
            lines.append(f'    ["{task_id}"] = {loc["id"]},')
    lines.append("}")
    milestone = catalogue["milestones"]["checks_side_task_milestones"]
    lines.append(f"side_task_milestone_base = {milestone['base_id']}")
    lines.append(f"side_task_milestone_maximum = {milestone['maximum']}")
    lines.append("artefact_locations = {")
    for loc in catalogue["locations"]:
        if loc["category"] == "checks_artefacts" and "quota_group" not in loc:
            lines.extend(f'    ["{alias}"] = {loc["id"]},' for alias in loc["aliases"])
    lines.append("}")
    milestone = catalogue["milestones"]["checks_kill_milestones"]
    lines.append(f"kill_milestone_base = {milestone['base_id']}")
    lines.append(f"kill_milestone_maximum = {milestone['maximum']}")
    for table_name in ("mutant_classes", "mutant_sections"):
        lines.append(table_name + " = {")
        lines.extend(f'    ["{key}"] = "{value}",' for key, value in catalogue[table_name].items())
        lines.append("}")
    for category, table_name in (
        ("checks_mutant_first_kills", "mutant_locations"),
        ("checks_faction_first_kills", "faction_locations"),
    ):
        lines.append(table_name + " = {")
        lines.extend(
            f'    ["{loc["key"]}"] = {loc["id"]},'
            for loc in catalogue["locations"]
            if loc["category"] == category and "quota_group" not in loc
        )
        lines.append("}")
    lines.append("pilot_ids = {[28052001]=true, [28052002]=true, [28052003]=true}")
    lines.append("location_categories = {")
    lines.extend(f'    [{loc["id"]}] = "{loc["category"]}",' for loc in catalogue["locations"])
    lines.extend(["}", "settlements = {"])
    for loc in catalogue["locations"]:
        for smart in loc.get("smarts", []):
            lines.append(
                f'    ["{smart}"] = {{id={loc["id"]}, level="{loc["level"]}", radius=50}},'
            )
    lines.append("}")
    limits = {
        **dict.fromkeys(CHECK_OPTIONS + REWARD_OPTIONS, 1),
        **dict.fromkeys(GEAR_OPTIONS, 2),
        **dict.fromkeys(QUANTITY_OPTIONS, 100),
        "goal": len(GOALS) - 1,
        "no_starting_weapons": 1,
        "zone_unlock_travel": 1,
        "pda_tracker": 1,
        **EXPANSION_LIMITS,
    }
    lines.append("config_limits = {")
    lines.extend(f'    ["{name}"] = {limit},' for name, limit in sorted(limits.items()))
    lines.append("}")
    lines.extend(tracker_lines(catalogue))
    lines.append("notice_cause_templates = {")
    lines.extend(
        f"    [{json.dumps(key)}]={json.dumps(value)}," for key, value in CAUSE_TEMPLATES.items()
    )
    lines.append("}")
    config_defaults = {
        "zone_unlock_travel": 0,
        "pda_tracker": 1,
        **EXPANSION_DEFAULTS,
        **LEGACY_CHECK_DEFAULTS,
        **LEGACY_REWARD_DEFAULTS,
    }
    lines.append("config_defaults = {")
    lines.extend(f'    ["{name}"]={value},' for name, value in sorted(config_defaults.items()))
    lines.append("}")
    require_safe_child(ROOT, "mod/gamedata/scripts/gamma_ap_catalog.script").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
    )


def package(
    source: Path, destination: Path, prefix: str = "", extras: dict[str, Path] | None = None
) -> None:
    if source.is_symlink() or source.is_junction():
        raise ValueError("Package sources cannot contain filesystem links")
    if not source.is_dir():
        raise ValueError("Package source directory is missing")
    entries = {}
    for path in source.rglob("*"):
        if "__pycache__" in path.parts:
            continue
        if path.is_symlink() or path.is_junction():
            raise ValueError("Package sources cannot contain filesystem links")
        if path.is_file():
            validate_package_file(path)
            entries[prefix + path.relative_to(source).as_posix()] = path
    entries.update(extras or {})
    for path in entries.values():
        validate_package_file(path)
    with ZipFile(destination, "w", compression=ZIP_DEFLATED) as archive:
        for name, path in sorted(entries.items()):
            info = ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o644 << 16
            # Only byte-verified generated/credited textures are binary; normalize text EOLs.
            payload = (
                path.read_bytes()
                if path.suffix == ".dds"
                else path.read_text(encoding="utf-8").encode("utf-8")
            )
            archive.writestr(info, payload)


def validate_package_file(path: Path) -> None:
    if path.is_symlink() or path.is_junction() or path.stat().st_nlink > 1:
        raise ValueError("Package files must be independent copies, without links")
    if path.name == Path(TEXTURE_PATH).name and path.read_bytes() == stash_icon():
        return
    if path.name == Path(SHOP_TEXTURE_PATH).name and path.read_bytes() == shop_icon():
        return
    if path.suffix not in {".py", ".json", ".script", ".xml", ".md", ".txt"}:
        raise ValueError(f"Unexpected package source type: {path.suffix}")


def main() -> None:
    generate_catalogues()
    generate_stash_icon(require_safe_child(ROOT, "mod"))
    generate_shop_icon(require_safe_child(ROOT, "mod"))
    destination = require_safe_child(ROOT, "dist")
    destination.mkdir(exist_ok=True)
    packages = [
        require_safe_child(ROOT, "dist/" + name)
        for name in (
            "gamma.apworld",
            "gamma-archipelago-mo2.zip",
            "gamma-archipelago-probes.zip",
            "gamma-archipelago-client.zip",
        )
    ]
    package(ROOT / "apworld/gamma", packages[0], "gamma/")
    package(ROOT / "mod", packages[1])
    shared_path = "gamedata/scripts/gamma_ap_paths.script"
    package(ROOT / "probes", packages[2], extras={shared_path: ROOT / "mod" / shared_path})
    package(
        ROOT / "src/gamma_archipelago",
        packages[3],
        "gamma_archipelago/",
        extras={
            "GammaArchipelagoClient.py": ROOT / "tools/packaged_client.py",
            "GammaArchipelagoConnect.py": ROOT / "tools/packaged_connect.py",
            "GAMMA-README.md": ROOT / "docs/portable-client.md",
            "GAMMA-requirements-ap.txt": ROOT / "requirements-ap.txt",
        },
    )
    hashes = [f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {path.name}" for path in packages]
    require_safe_child(ROOT, "dist/SHA256SUMS").write_text(
        "\n".join(hashes) + "\n", encoding="ascii"
    )
    print("Built deterministic APWorld, companion and MO2 packages.")


if __name__ == "__main__":
    main()
