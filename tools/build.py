"""Produce deterministic packages and the two generated catalogue copies."""

import hashlib
import json
import sys
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tools"))
from build_activity_catalog import activity_lines  # noqa: E402
from build_notice_strings import generate_notice_strings  # noqa: E402
from build_shop_icon import SHOP_TEXTURE_PATH, generate_shop_icon, shop_icon  # noqa: E402
from build_shop_strings import generate_shop_strings  # noqa: E402
from build_stash_icon import TEXTURE_PATH, generate_stash_icon, stash_icon  # noqa: E402
from build_tracker_catalog import tracker_lines  # noqa: E402

from gamma_archipelago.configuration import (  # noqa: E402
    CHECK_OPTIONS,
    GEAR_OPTIONS,
    GOALS,
    QUANTITY_OPTIONS,
    REWARD_OPTIONS,
)
from gamma_archipelago.expansion_settings import (  # noqa: E402
    EXPANSION_DEFAULTS,
    EXPANSION_LIMITS,
    LEGACY_CHECK_DEFAULTS,
    LEGACY_REWARD_DEFAULTS,
)
